"""Safe streaming storage for uploaded video recordings."""

from __future__ import annotations

from pathlib import Path
from uuid import uuid4

from fastapi import UploadFile

from .dataset_manager import (
    ALLOWED_VIDEO_TYPES,
    MAX_UPLOAD_BYTES,
    RAW_DIR,
)


CHUNK_SIZE = 1024 * 1024  # 1 MB


# ---------------------------------------------------------------------
# Upload exceptions
# ---------------------------------------------------------------------

class RecorderError(Exception):
    """Base exception for video upload operations."""


class UploadTooLargeError(RecorderError):
    """Uploaded video exceeds the maximum allowed size."""


class UnsupportedVideoTypeError(RecorderError):
    """Uploaded video format is not supported."""


class EmptyUploadError(RecorderError):
    """Uploaded video is empty."""


# ---------------------------------------------------------------------
# Content type detection
# ---------------------------------------------------------------------

def infer_content_type(
    filename: str | None,
    content_type: str | None,
) -> str:
    """
    Determine the supported video MIME type.

    Browser MediaRecorder uploads sometimes use
    application/octet-stream. In that case, use the filename extension.
    """

    normalized_type = (
        (content_type or "")
        .split(";")[0]
        .strip()
        .lower()
    )

    if normalized_type in ALLOWED_VIDEO_TYPES:
        return normalized_type

    # Fallback for generic or missing browser MIME types.
    if normalized_type in ("", "application/octet-stream"):
        extension = Path(filename or "").suffix.lower()

        for mime_type, allowed_extension in ALLOWED_VIDEO_TYPES.items():
            if extension == allowed_extension:
                return mime_type

    raise UnsupportedVideoTypeError(
        "Unsupported video format. "
        "Use WebM, MP4 or MOV."
    )


# ---------------------------------------------------------------------
# Upload storage
# ---------------------------------------------------------------------

async def save_video_upload(
    upload: UploadFile,
) -> tuple[str, int, str]:
    """
    Stream an uploaded video to dataset/raw/.

    Returns:
        (stored_filename, file_size, content_type)

    The stored filename is always generated by the application.
    The original client filename is never used as a filesystem path.
    """

    content_type = infer_content_type(
        upload.filename,
        upload.content_type,
    )

    extension = ALLOWED_VIDEO_TYPES[content_type]

    RAW_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    stored_filename = f"{uuid4().hex}{extension}"
    destination = RAW_DIR / stored_filename

    total_size = 0

    try:
        with destination.open("xb") as output:
            while True:
                chunk = await upload.read(CHUNK_SIZE)

                if not chunk:
                    break

                total_size += len(chunk)

                if total_size > MAX_UPLOAD_BYTES:
                    raise UploadTooLargeError(
                        "Maximum video size is 100 MB."
                    )

                output.write(chunk)

        if total_size == 0:
            raise EmptyUploadError(
                "The uploaded video is empty."
            )

        return (
            stored_filename,
            total_size,
            content_type,
        )

    except Exception:
        # Never leave an incomplete upload behind.
        destination.unlink(missing_ok=True)
        raise

    finally:
        try:
            await upload.close()
        except Exception:
            pass